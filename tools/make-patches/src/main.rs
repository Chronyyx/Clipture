//! Release tool: zstd `--patch-from` patches from earlier releases to a new
//! runtime, plus the unsigned `patches-v1.json` that release CI signs.
//! The app's `updates::patches` module applies them (ADR 0020).
//!
//! make-patches <new runtime dir> <version> <previous releases dir> <out dir>
//!
//! `previous releases dir` holds one directory per earlier version, each with
//! that release's runtime assets under their asset names. Asset URLs use
//! GitHub releases, or `CLIPTURE_TEST_RELEASE_ORIGIN` for a sandbox mirror.
use serde::Serialize;
use sha2::{Digest, Sha256};
use std::{fs, io, path::Path};
use zstd::zstd_safe::{CCtx, CParameter};

/// The runtime files of the signed manifest, as paths inside the runtime.
const PATHS: [&str; 5] = ["clipture.exe", "clipture_engine.exe", "ffmpeg.exe", "assets/default.mp3", "assets/option2.wav"];
/// Must not exceed the window the app decodes with (2^27, 128 MiB).
const WINDOW_LOG: u32 = 27;
const LEVEL: i32 = 19;

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct Patch { path: String, from_sha256: String, sha256: String, size: u64, url: String }

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct PatchList { schema_version: u32, version: String, patches: Vec<Patch> }

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [runtime, version, previous, out] = args.as_slice() else {
        eprintln!("usage: make-patches <new runtime dir> <version> <previous releases dir> <out dir>");
        std::process::exit(2);
    };
    let origin = std::env::var("CLIPTURE_TEST_RELEASE_ORIGIN").unwrap_or_else(|_| "https://github.com".into());
    let base = format!("{}/Chronyyx/Clipture/releases/download", origin.trim_end_matches('/'));
    match write_patches(runtime.as_ref(), version, previous.as_ref(), out.as_ref(), &base) {
        Ok(count) => println!("{count} patches written to {out}"),
        Err(error) => {
            eprintln!("make-patches: {error}");
            std::process::exit(1);
        }
    }
}

/// `clipture.exe.from-<16 hex>.zst`, the name the app expects.
fn file_name(path: &str, from_sha256: &str) -> String {
    format!("{}.from-{}.zst", path.rsplit('/').next().unwrap_or(path), &from_sha256[..16])
}

fn create(old: &[u8], new: &[u8]) -> io::Result<Vec<u8>> {
    let failed = |code: usize| io::Error::other(zstd::zstd_safe::get_error_name(code));
    let mut context = CCtx::create();
    for parameter in [CParameter::CompressionLevel(LEVEL), CParameter::EnableLongDistanceMatching(true), CParameter::WindowLog(WINDOW_LOG)] {
        context.set_parameter(parameter).map_err(failed)?;
    }
    context.ref_prefix(old).map_err(failed)?;
    let mut patch = vec![0_u8; zstd::zstd_safe::compress_bound(new.len())];
    let written = context.compress2(&mut patch[..], new).map_err(failed)?;
    patch.truncate(written);
    Ok(patch)
}

fn hex(bytes: &[u8]) -> String { format!("{:x}", Sha256::digest(bytes)) }

/// Skips unchanged files and patches not meaningfully smaller than the file.
fn write_patches(runtime: &Path, version: &str, previous: &Path, out: &Path, base: &str) -> io::Result<usize> {
    fs::create_dir_all(out)?;
    let mut releases: Vec<_> = fs::read_dir(previous)?.flatten().filter(|entry| entry.path().is_dir()).collect();
    releases.sort_by_key(|entry| entry.file_name());
    let mut patches: Vec<Patch> = Vec::new();
    for release in releases {
        for path in PATHS {
            let old_path = release.path().join(path.rsplit('/').next().unwrap_or(path));
            let (Ok(old), Ok(new)) = (fs::read(&old_path), fs::read(runtime.join(path))) else { continue };
            if old == new { continue; }
            let patch = create(&old, &new)?;
            if patch.len() as u64 * 10 > new.len() as u64 * 9 { continue; }
            let from_sha256 = hex(&old);
            if patches.iter().any(|existing| existing.path == path && existing.from_sha256 == from_sha256) { continue; }
            let name = file_name(path, &from_sha256);
            fs::write(out.join(&name), &patch)?;
            patches.push(Patch { path: path.into(), from_sha256, sha256: hex(&patch), size: patch.len() as u64, url: format!("{base}/v{version}/{name}") });
        }
    }
    let list = PatchList { schema_version: 1, version: version.into(), patches };
    fs::write(out.join("patches-v1.json"), serde_json::to_vec_pretty(&list).map_err(io::Error::other)?)?;
    Ok(list.patches.len())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Also generated by src-tauri's `updates::patches` tests.
    fn fixture_old() -> Vec<u8> { (0..65_536_usize).map(|index| ((index * 7919) % 251) as u8).collect() }
    fn fixture_new() -> Vec<u8> {
        let mut bytes = fixture_old();
        bytes[1000..1100].fill(0x5A);
        bytes.extend_from_slice(b"tail");
        bytes
    }

    /// The committed fixture is exactly what this tool produces. The app's
    /// tests apply and parse the same files, so a change to the zstd version,
    /// parameters, naming or list format fails here or there, never silently.
    #[test]
    fn output_matches_the_fixture_the_app_tests_against() {
        let root = std::env::temp_dir().join(format!("make-patches-test-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(root.join("runtime")).unwrap();
        fs::create_dir_all(root.join("previous/1.0.0")).unwrap();
        fs::write(root.join("previous/1.0.0/clipture.exe"), fixture_old()).unwrap();
        fs::write(root.join("runtime/clipture.exe"), fixture_new()).unwrap();
        fs::write(root.join("previous/1.0.0/ffmpeg.exe"), b"same").unwrap();
        fs::write(root.join("runtime/ffmpeg.exe"), b"same").unwrap();
        let count = write_patches(&root.join("runtime"), "1.1.0", &root.join("previous"), &root.join("out"),
            "https://github.com/Chronyyx/Clipture/releases/download").unwrap();
        assert_eq!(count, 1);
        let fixtures = Path::new(env!("CARGO_MANIFEST_DIR")).join("fixtures");
        let name = file_name("clipture.exe", &hex(&fixture_old()));
        if std::env::var_os("UPDATE_FIXTURES").is_some() {
            fs::create_dir_all(&fixtures).unwrap();
            fs::copy(root.join("out").join(&name), fixtures.join("clipture.exe.patch.zst")).unwrap();
            fs::copy(root.join("out/patches-v1.json"), fixtures.join("patches-v1.json")).unwrap();
        }
        assert_eq!(fs::read(root.join("out").join(&name)).unwrap(), fs::read(fixtures.join("clipture.exe.patch.zst")).unwrap(),
            "patch bytes changed; rerun with UPDATE_FIXTURES=1 only if the app still decodes them");
        assert_eq!(fs::read(root.join("out/patches-v1.json")).unwrap(), fs::read(fixtures.join("patches-v1.json")).unwrap());
        let _ = fs::remove_dir_all(&root);
    }
}
